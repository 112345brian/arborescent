CHECKERS = list(all_checkers().values())


def services(runner: FakeToolRunner | None = None, cache: Path | None = None) -> Services:
    return Services(FsScanner(cache), runner or FakeToolRunner(), CHECKERS, LocalFileSystem(), SystemClock(), default_engines())


def commit_generated(repo: Path) -> None:
    policy = mini_policy()
    scan = FsScanner().scan(policy, repo)
    for rel, text in generate(policy, sorted(scan.known), by_name(policy.type_checkers)).items():
        write_files(repo, {rel: text})


# --- drift -------------------------------------------------------------------------------------------------------


def test_missing_optional_configs_are_not_drift_and_generated_config_drift_is_advisory(repo: Path) -> None:
    report = run_check(mini_policy(), repo, services(), Options(tools=False))
    assert report.ok and report.drift == []
    commit_generated(repo)
    assert run_check(mini_policy(), repo, services(), Options(tools=False)).ok
    write_files(repo, {"tach.toml": "# hand edited\n"})
    report = run_check(mini_policy(), repo, services(), Options(tools=False))
    assert report.ok and report.drift == []  # user-owned files are not compared to Arborescent presets


def test_generated_preset_drift_is_informational(repo: Path) -> None:
    commit_generated(repo)
    write_files(repo, {"tach.toml": "# Generated by `arborescent generate`\n# changed\n"})
    report = run_check(mini_policy(), repo, services(), Options(tools=False))
    assert report.ok and report.drift == ["tach.toml: differs from the policy; run `arborescent generate`"]


def test_generate_creates_only_missing_presets_and_never_overwrites(repo: Path, capsys) -> None:  # type: ignore[no-untyped-def]
    write_files(repo, {"ruff.toml": "# project-owned\n"})
    policy_file = repo / "arborescent.toml"
    policy_file.write_text('sources = ["app"]\nrings = ["domain"]\n[ring.domain]\nexternal = []\n[classify]\n"app" = "domain"\n', encoding="utf-8")
    svc = services()

    assert main(["--config", str(policy_file), "generate"], svc) == 0
    assert (repo / "ruff.toml").read_text(encoding="utf-8") == "# project-owned\n"
    assert (repo / "tach.toml").read_text(encoding="utf-8").startswith("# Generated by `arborescent generate`")
    assert "wrote tach.toml" in capsys.readouterr().out


def test_a_new_module_changes_the_generated_configs(repo: Path) -> None:
    commit_generated(repo)
    write_files(repo, {"app/domain2.py": ""})
    report = run_check(mini_policy(classify={"app": "domain", "app.*": "domain"}), repo, services(), Options(tools=False))
    assert any(d.startswith("tach.toml") for d in report.drift)


