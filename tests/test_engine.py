@pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")
def test_changed_mode_does_not_send_deleted_python_paths_to_file_engines(repo: Path) -> None:
    commit_generated(repo)
    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", "add", "-A"], cwd=repo, check=True)
    subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "-m", "base"], cwd=repo, check=True)
    (repo / "app/domain.py").unlink()

    class GitBackedFake(FakeToolRunner):
        def run(self, argv, cwd, timeout=600.0):  # type: ignore[no-untyped-def]
            self.calls.append(list(argv))
            if argv[0] == "git":
                result = subprocess.run(argv, cwd=cwd, capture_output=True, text=True, check=False)
                return ToolResult(result.returncode, result.stdout, result.stderr)
            return super().run(argv, cwd, timeout)

    runner = GitBackedFake({"lint-imports", "tach", "tach-external", "ruff", "ty"}, {"ruff": ToolResult(0, "[]", "")})
    services_with_fake = Services(FsScanner(runner=runner), runner, CHECKERS, LocalFileSystem(), SystemClock(), default_engines())

    report = run_check(mini_policy(), repo, services_with_fake, Options(changed="HEAD", use_baseline=False))

    assert not any("app/domain.py" in call for call in runner.calls if call[0] in {"ruff", "ty"})
    assert not any(engine.name in {"ruff", "ty"} and engine.status == "fail" for engine in report.engines)


