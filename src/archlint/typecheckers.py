"""Type-checker adapters: pyright, basedpyright and the Rust-based ty and pyrefly.

Every setting name below was verified by running the installed tool (pyright 1.1.414, basedpyright 1.40.2,
ty 0.0.91, pyrefly 1.4.0): an unknown pyright/ty key is reported by the tool, and an unknown pyrefly error
kind makes pyrefly drop the WHOLE config and fall back to auto-configuration, which ``passed`` treats as a failure.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from dataclasses import dataclass

from .domain import Policy, ToolResult

__all__ = ["BasedPyright", "Pyrefly", "Pyright", "Ty", "all_checkers", "by_name"]

# Deliberately NOT enabled: reportImportCycles. Measured on a 314-file codebase it took pyright from 11.5 s to more than
# 8 minutes, and cycles are already caught by tach (forbid_circular_dependencies) and import-linter.
# The Rust-like settings: nothing is Unknown, matches are exhaustive, an ignore comment can't hide an error.
_PYRIGHT_STRICT: dict[str, object] = {
    "typeCheckingMode": "strict",
    "enableTypeIgnoreComments": False,
    "reportMatchNotExhaustive": "error",
    "reportUnknownParameterType": "error",
    "reportUnknownArgumentType": "error",
    "reportUnknownVariableType": "error",
    "reportUnknownMemberType": "error",
    "reportUnknownLambdaType": "error",
    "reportMissingTypeStubs": "error",
    "reportMissingParameterType": "error",
    "reportUnnecessaryTypeIgnoreComment": "error",
    "reportImplicitOverride": "error",
    "reportPrivateUsage": "error",
    "reportUntypedFunctionDecorator": "error",
    "reportUnnecessaryCast": "error",
    "reportUnnecessaryComparison": "error",
    "reportUnnecessaryIsInstance": "error",
    "strictListInference": True,
    "strictDictionaryInference": True,
    "strictSetInference": True,
}
_BASED_EXTRA: dict[str, object] = {"reportAny": "error", "reportExplicitAny": "error", "reportUnreachable": "error"}


def _pyright_json(policy: Policy, paths: Sequence[str], extra: dict[str, object]) -> str:
    cfg: dict[str, object] = {
        **_PYRIGHT_STRICT,
        **extra,
        "pythonVersion": policy.python,
        "include": list(paths),
        "exclude": ["**/__pycache__", "**/node_modules", "**/.venv"],
    }
    return json.dumps(cfg, indent=2) + "\n"


@dataclass(frozen=True)
class Pyright:
    name: str = "pyright"
    executable: str = "pyright"
    config_file: str = "pyrightconfig.json"

    def render_config(self, policy: Policy, paths: Sequence[str]) -> str:
        return _pyright_json(policy, paths, {})

    def command(self, files: Sequence[str]) -> list[str]:
        return [self.executable, *files]

    def passed(self, result: ToolResult) -> bool:
        return result.returncode == 0


@dataclass(frozen=True)
class BasedPyright:
    name: str = "basedpyright"
    executable: str = "basedpyright"
    config_file: str = "pyrightconfig.json"

    def render_config(self, policy: Policy, paths: Sequence[str]) -> str:
        return _pyright_json(policy, paths, _BASED_EXTRA)

    def command(self, files: Sequence[str]) -> list[str]:
        return [self.executable, *files]

    def passed(self, result: ToolResult) -> bool:
        return result.returncode == 0


@dataclass(frozen=True)
class Ty:
    name: str = "ty"
    executable: str = "ty"
    config_file: str = "ty.toml"

    def render_config(self, policy: Policy, paths: Sequence[str]) -> str:
        return (
            "# Generated by `archlint generate` from the [tool.archlint] policy. Do not edit; change the policy.\n"
            f'[environment]\npython-version = "{policy.python}"\n\n'
            "[analysis]\nrespect-type-ignore-comments = false\n\n"
            '[rules]\nall = "error"\n\n'
            "[terminal]\nerror-on-warning = true\n"
        )

    def command(self, files: Sequence[str]) -> list[str]:
        return [self.executable, "check", *files]

    def passed(self, result: ToolResult) -> bool:
        return result.returncode == 0


@dataclass(frozen=True)
class Pyrefly:
    name: str = "pyrefly"
    executable: str = "pyrefly"
    config_file: str = "pyrefly.toml"

    def render_config(self, policy: Policy, paths: Sequence[str]) -> str:
        kinds = (
            "implicit-any", "implicit-any-parameter", "unannotated-parameter", "unannotated-return",
            "unknown-argument-type", "unknown-attribute-type", "unknown-return-type", "unknown-variable-type",
            "non-exhaustive-match", "unused-ignore", "missing-override-decorator",
            "unnecessary-comparison", "redundant-cast", "untyped-function-decorator", "explicit-any",
        )  # fmt: skip
        includes = ", ".join(f'"{p}"' for p in paths)
        body = "".join(f"{k} = true\n" for k in kinds)
        return (
            "# Generated by `archlint generate` from the [tool.archlint] policy. Do not edit; change the policy.\n"
            f"project-includes = [{includes}]\n"
            f'python-version = "{policy.python}"\n'
            'enabled-ignores = ["pyrefly"]\n\n'
            f"[errors]\n{body}"
        )

    def command(self, files: Sequence[str]) -> list[str]:
        return [self.executable, "check", *files]

    def passed(self, result: ToolResult) -> bool:
        text = result.stdout + result.stderr
        return result.returncode == 0 and "failed to parse" not in text and "Extra keys found" not in text


def all_checkers() -> dict[str, Pyright | BasedPyright | Ty | Pyrefly]:
    return {c.name: c for c in (Pyright(), BasedPyright(), Ty(), Pyrefly())}


def by_name(names: Sequence[str]) -> list[Pyright | BasedPyright | Ty | Pyrefly]:
    table = all_checkers()
    unknown = [n for n in names if n not in table]
    if unknown:
        raise ValueError(f"unknown type checker(s) {unknown}; choose from {sorted(table)}")
    return [table[n] for n in names]
