"""Which config belongs to Arborescent and which is the project's own.

``generate`` only creates missing files and ``drift`` only inspects files that carry the generated header. Reading
follows the same rule: a project's own configuration is intentional and always wins; a generated file is used only when it
is recognisably Arborescent's. A hand-written file that happens to share a generated name is never adopted.
"""

from __future__ import annotations

from pathlib import Path
from typing import Protocol

__all__ = ["GENERATED_MARKER", "TextFiles", "has_own_importlinter_config", "is_generated"]

GENERATED_MARKER = "# Generated by `arborescent generate`"

class TextFiles(Protocol):
    """What these checks need to know about files; the ``FileSystem`` port satisfies it."""

    def is_file(self, path: Path) -> bool: ...

    def read_text(self, path: Path) -> str: ...


# Where `lint-imports` looks for configuration, with the marker that shows a file really configures import-linter
# (a pyproject.toml or setup.cfg without that section is not config).
_IMPORTLINTER_FILES = (
    ("pyproject.toml", "[tool.importlinter"),
    ("setup.cfg", "[importlinter"),
    ("tox.ini", "[importlinter"),
)


def is_generated(fs: TextFiles, path: Path) -> bool:
    """Whether ``path`` exists and carries the header ``generate`` writes."""
    return fs.is_file(path) and fs.read_text(path).startswith(GENERATED_MARKER)


def has_own_importlinter_config(fs: TextFiles, root: Path) -> bool:
    """Whether the project configured import-linter itself, in any file ``lint-imports`` discovers on its own."""
    return fs.is_file(root / ".importlinter") or any(
        fs.is_file(root / name) and marker in fs.read_text(root / name) for name, marker in _IMPORTLINTER_FILES
    )
