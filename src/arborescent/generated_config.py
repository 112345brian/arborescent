"""Which config belongs to Arborescent and which is the project's own.

``generate`` only creates missing files and ``drift`` only inspects files that carry the generated header. Reading
follows the same rule: a project's own configuration is intentional and always wins; a generated file is used only when it
is recognisably Arborescent's. A hand-written file that happens to share a generated name is never adopted.
``windows_tach_config`` is the one rewrite of a project's ``tach.toml``, and only ever of a temporary copy (#214).
"""

from __future__ import annotations

import re
import tomllib
from collections.abc import Sequence
from pathlib import Path, PureWindowsPath
from typing import Protocol

__all__ = [
    "GENERATED_MARKER",
    "HEADER",
    "IMPORT_LINTER_FILE",
    "TACH_FILE",
    "TextFiles",
    "has_own_importlinter_config",
    "is_generated",
    "toml_list",
    "toml_quote",
    "windows_tach_config",
]

GENERATED_MARKER = "# Generated by `arborescent generate`"
HEADER = f"{GENERATED_MARKER} from the [tool.arborescent] policy. Do not edit; change the policy.\n"
IMPORT_LINTER_FILE = "arborescent-importlinter.toml"
TACH_FILE = "tach.toml"


def toml_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def toml_list(items: Sequence[str], indent: str = "") -> str:
    if not items:
        return "[]"
    if len(", ".join(items)) < 90:
        return "[" + ", ".join(toml_quote(i) for i in items) + "]"
    return "[\n" + "".join(f"{indent}    {toml_quote(i)},\n" for i in items) + indent + "]"


# The top-level `source_roots = [...]` of a tach.toml: strings, commas, whitespace and comment lines up to the bracket.
_SOURCE_ROOTS = re.compile(
    r"""^source_roots[ \t]*=[ \t]*\[(?:\s|,|#[^\n]*\n|"(?:[^"\\\n]|\\.)*"|'[^'\n]*')*\]""", re.MULTILINE
)


def windows_tach_config(text: str) -> str | None:
    """A ``tach.toml`` with its forward-slash ``source_roots`` spelled with backslashes, or ``None`` to use it as it is.

    tach 0.35.x on Windows prunes its file walk by comparing folder names with the root as written, so it reads nothing
    under a root such as ``libs/a/src`` and then reports every dependency declared there as unused (#214). Globs are
    left as written, and a root outside the project folder (absolute or ``..``) leaves the whole file alone.
    """
    try:
        roots = tomllib.loads(text).get("source_roots")
        if not isinstance(roots, list) or not all(isinstance(root, str) for root in roots):
            return None
        paths = [PureWindowsPath(root) for root in roots]
        if any(path.anchor or ".." in path.parts for path in paths):
            return None
        changed = [root if set("*?[{") & set(root) else str(path) for root, path in zip(roots, paths, strict=True)]
        if not any("/" in root and root != new for root, new in zip(roots, changed, strict=True)):
            return None
        line = f"source_roots = [{', '.join(toml_quote(root) for root in changed)}]"
        rewritten = _SOURCE_ROOTS.sub(lambda _: line, text, count=1)
        return rewritten if tomllib.loads(rewritten).get("source_roots") == changed else None
    except tomllib.TOMLDecodeError:
        return None


class TextFiles(Protocol):
    """What these checks need to know about files; the ``FileSystem`` port satisfies it."""

    def is_file(self, path: Path) -> bool: ...

    def read_text(self, path: Path) -> str: ...


# Where `lint-imports` looks for configuration, with the marker that shows a file really configures import-linter
# (a pyproject.toml or setup.cfg without that section is not config).
_IMPORTLINTER_FILES = (
    ("pyproject.toml", "[tool.importlinter"),
    ("setup.cfg", "[importlinter"),
    ("tox.ini", "[importlinter"),
)


def is_generated(fs: TextFiles, path: Path) -> bool:
    """Whether ``path`` exists and carries the header ``generate`` writes."""
    return fs.is_file(path) and fs.read_text(path).startswith(GENERATED_MARKER)


def has_own_importlinter_config(fs: TextFiles, root: Path) -> bool:
    """Whether the project configured import-linter itself, in any file ``lint-imports`` discovers on its own."""
    return fs.is_file(root / ".importlinter") or any(
        fs.is_file(root / name) and marker in fs.read_text(root / name) for name, marker in _IMPORTLINTER_FILES
    )
